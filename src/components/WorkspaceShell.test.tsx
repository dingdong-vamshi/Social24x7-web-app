import { beforeEach, describe, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, within, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import { WorkspaceShell } from './WorkspaceShell'
import { flyoutPosition } from './flyout-position'
vi.mock('../auth/AuthContext', () => ({ useAuth: () => ({ profile: { id: 'qa', display_name: 'QA' }, access: { seller_status: 'approved', creator_status: 'approved' } }) }))
vi.mock('./AccountMenu', () => ({ AccountMenu: () => null }))
vi.mock('../pages/Social', () => ({ WorkspaceNotifications: () => <button>Notifications</button> }))
beforeEach(() => localStorage.clear())
describe('original-depth workspace navigation', () => {
  it('opens an already-expanded group with one click from collapsed navigation', async () => {
    render(<MemoryRouter initialEntries={['/partner/seller/returns']}><WorkspaceShell role="seller">QA</WorkspaceShell></MemoryRouter>)
    await userEvent.click(screen.getByRole('button', { name: 'Collapse navigation' }))
    expect(screen.getByRole('button', { name: 'Orders submenu' })).toHaveAttribute('aria-expanded', 'false')
    await userEvent.click(screen.getByRole('button', { name: 'Orders submenu' }))
    expect(screen.getByRole('link', { name: 'Manage Returns' })).toBeVisible()
  })
  it('highlights a return deep link without inline expansion or saved expansion state', async () => {
    render(<MemoryRouter initialEntries={['/partner/seller/returns']}><WorkspaceShell role="seller">QA</WorkspaceShell></MemoryRouter>)
    expect(screen.getByRole('button', { name: 'Orders submenu' })).toHaveAttribute('aria-expanded', 'false')
    expect(screen.getByRole('button', { name: 'Orders submenu' }).parentElement).toHaveClass('current-group')
    await userEvent.click(screen.getByRole('button', { name: 'Orders submenu' }))
    expect(screen.getByRole('link', { name: 'Manage Returns' })).toHaveAttribute('aria-current', 'page')
    expect(screen.getByRole('link', { name: 'Return Settings' })).toHaveAttribute('href', '/partner/seller/orders/return-settings')
    await userEvent.keyboard('{Escape}')
    expect(screen.queryByRole('link', { name: 'Manage Returns' })).not.toBeInTheDocument()
    expect(localStorage.getItem('social24.navigation.seller.qa')).toBeNull()
  })
  it('keeps Social directly after Business Chat and labels original Soon items', async () => {
    render(<MemoryRouter><WorkspaceShell role="seller">QA</WorkspaceShell></MemoryRouter>)
    const links = screen.getAllByRole('link').map(link => link.textContent)
    expect(links[links.indexOf('Business Chat') + 1]).toBe('Social')
    expect(links[links.indexOf('Social') + 1]).toBe('Team & verification')
    await userEvent.click(screen.getByRole('button', { name: 'Products submenu' }))
    expect(screen.getByRole('link', { name: 'Product Ratings Soon' })).toHaveAttribute('href', '/partner/seller/products/ratings')
  })
  it('gives Creators direct Social, collaboration and payment-status access', () => {
    render(<MemoryRouter><WorkspaceShell role="creator">QA</WorkspaceShell></MemoryRouter>)
    expect(screen.getByRole('link', { name: 'Social' })).toHaveAttribute('href', '/partner/creator/social')
    expect(screen.getByRole('link', { name: 'Collaborations' })).toHaveAttribute('href', '/partner/creator/collab')
    expect(screen.getByRole('link', { name: 'Payments' })).toHaveAttribute('href', '/partner/creator/payments')
    expect(screen.queryByRole('button', { name: /submenu/ })).not.toBeInTheDocument()
  })
  it.each([['Orders', 3], ['Products', 6], ['Logistics', 5], ['Marketing', 5], ['Affiliate', 2]])('preserves every %s destination in a portal', async (group, count) => {
    render(<MemoryRouter><WorkspaceShell role="seller">QA</WorkspaceShell></MemoryRouter>)
    await userEvent.click(screen.getByRole('button', { name: `${group} submenu` }))
    const panel = screen.getByRole('navigation', { name: `${group} navigation` })
    expect(within(panel).getAllByRole('link')).toHaveLength(Number(count))
    expect(panel.closest('aside')).toBeNull()
    expect(document.querySelector('.workspace-nav-children')).toBeNull()
  })
  it('opens with keyboard, traverses links, escapes to trigger and does not trap Tab', async () => {
    render(<MemoryRouter><WorkspaceShell role="seller">QA</WorkspaceShell></MemoryRouter>)
    const trigger = screen.getByRole('button', { name: 'Orders submenu' })
    trigger.focus()
    await userEvent.keyboard('{ArrowRight}')
    expect(screen.getByRole('link', { name: 'Manage Orders' })).toHaveFocus()
    await userEvent.keyboard('{End}')
    expect(screen.getByRole('link', { name: 'Return Settings' })).toHaveFocus()
    await userEvent.tab()
    expect(screen.getByRole('button', { name: 'Products submenu' })).toHaveFocus()
    await userEvent.keyboard('{Enter}{Escape}')
    expect(screen.getByRole('button', { name: 'Products submenu' })).toHaveFocus()
    expect(screen.queryByRole('navigation', { name: 'Products navigation' })).not.toBeInTheDocument()
  })
  it('switches groups and closes on outside input and navigation', async () => {
    render(<MemoryRouter><WorkspaceShell role="seller">QA</WorkspaceShell></MemoryRouter>)
    await userEvent.click(screen.getByRole('button', { name: 'Orders submenu' }))
    await userEvent.click(screen.getByRole('button', { name: 'Products submenu' }))
    expect(screen.queryByRole('navigation', { name: 'Orders navigation' })).not.toBeInTheDocument()
    fireEvent.pointerDown(document.body)
    expect(screen.queryByRole('navigation', { name: 'Products navigation' })).not.toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: 'Orders submenu' }))
    await userEvent.click(screen.getByRole('link', { name: 'Manage Returns' }))
    expect(screen.queryByRole('navigation', { name: 'Orders navigation' })).not.toBeInTheDocument()
  })
  it.each([1440, 1280, 1024, 768, 430, 390, 360])('clamps flyouts within a %ipx viewport', width => {
    const position = flyoutPosition({ left: 10, right: 235, top: 740, bottom: 782 }, 250, 360, width, 800)
    expect(position.left).toBeGreaterThanOrEqual(12)
    expect(position.left + position.width).toBeLessThanOrEqual(width - 12)
    expect(position.top + 360).toBeLessThanOrEqual(788)
  })
  it('opens on mouse entry, preserves the bridge into the panel and closes after leaving', async () => {
    render(<MemoryRouter><WorkspaceShell role="seller">QA</WorkspaceShell></MemoryRouter>)
    const user = userEvent.setup()
    await user.hover(screen.getByRole('button', { name: 'Orders submenu' }))
    const panel = screen.getByRole('navigation', { name: 'Orders navigation' })
    await user.hover(panel)
    expect(panel).toBeVisible()
    await user.hover(screen.getByRole('button', { name: 'Products submenu' }))
    expect(screen.queryByRole('navigation', { name: 'Orders navigation' })).not.toBeInTheDocument()
    await user.unhover(screen.getByRole('button', { name: 'Products submenu' }))
    await waitFor(() => expect(screen.queryByRole('navigation', { name: 'Products navigation' })).not.toBeInTheDocument())
  })
  it('supports touch-style click toggling without hover and closes on outside tap', () => {
    render(<MemoryRouter><WorkspaceShell role="seller">QA</WorkspaceShell></MemoryRouter>)
    const trigger = screen.getByRole('button', { name: 'Orders submenu' })
    fireEvent.click(trigger, { detail: 1 })
    expect(trigger).toHaveAttribute('aria-expanded', 'true')
    fireEvent.click(trigger, { detail: 1 })
    expect(trigger).toHaveAttribute('aria-expanded', 'false')
    fireEvent.click(trigger, { detail: 1 })
    fireEvent.pointerDown(document.body)
    expect(trigger).toHaveAttribute('aria-expanded', 'false')
  })
})
